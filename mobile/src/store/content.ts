/** Cada elemento de contenido es también un fragmento citable por el chat. */
export function chunksFromContent(items: readonly ContentItem[]): Chunk[] {
  return items.map((i) => ({
    id: i.id,
    documentId: i.documentId,
    page: i.page,
    klass: i.klass,
    section: i.title,
    text: i.text,
    ...(i.external ? { external: i.external } : {}),
  }));
}
